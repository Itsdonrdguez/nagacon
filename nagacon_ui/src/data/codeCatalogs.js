function normalizeCatalog(entries, type) {
  return entries.map(([value, description]) => ({
    value,
    label: `${value} - ${description}`,
    description,
    type,
    searchText: `${value} ${description}`.toLowerCase(),
  }))
}

export const FSC_CODE_OPTIONS = normalizeCatalog(FSC_OPTIONS, 'fsc')
export const NAICS_CODE_OPTIONS = normalizeCatalog(NAICS_OPTIONS, 'naics')

export function withCustomOptions(baseOptions, selectedValues = [], type = 'code') {
  const seen = new Set(baseOptions.map((option) => option.value))
  const extras = (selectedValues || [])
    .map((value) => String(value || '').trim())
    .filter(Boolean)
    .filter((value) => !seen.has(value))
    .map((value) => ({
      value,
      label: `${value} - Custom ${type.toUpperCase()} code`,
      description: `Custom ${type.toUpperCase()} code`,
      type,
      searchText: `${value} custom ${type} code`.toLowerCase(),
    }))
  return [...baseOptions, ...extras]
}
