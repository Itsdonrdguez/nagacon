// Utility functions for theme usage
export const getColor = (color, shade = 500) => {
  if (typeof theme.colors[color] === 'string') {
    return theme.colors[color]
  }
  return theme.colors[color]?.[shade] || theme.colors[color]?.[500] || color
}

export const getSpacing = (size) => theme.spacing[size] || size
export const getBorderRadius = (size) => theme.borderRadius[size] || size
export const getFontSize = (size) => theme.fontSize[size] || size
export const getFontWeight = (weight) => theme.fontWeight[weight] || weight
